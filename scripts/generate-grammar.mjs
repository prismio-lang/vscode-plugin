// Generates syntaxes/prismio.tmLanguage.json from the compiler's token tables.
//
//   node scripts/generate-grammar.mjs                 from syntaxes/tokens.json (the committed snapshot)
//   node scripts/generate-grammar.mjs --refresh       first re-dump the snapshot with `prismio dump-tokens`
//   node scripts/generate-grammar.mjs --check         write nothing; exit 1 if the grammar is stale
//
// The words of the language are never typed here: keywords, word operators, literals, the built-in
// types, the operators and the contextual keywords all come from `prismio dump-tokens`, which reads
// the compiler's own tables. What is here is only how a class of token is coloured. TextMate cannot
// see context, so a contextual keyword is matched only where the table says it is a marker or the
// start of a declaration; the server's semantic tokens colour the rest.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokensPath = join(root, "syntaxes", "tokens.json");
const grammarPath = join(root, "syntaxes", "prismio.tmLanguage.json");

const escape = (text) => text.replace(/[.*+?^${}()|[\]\\\/-]/g, "\\$&");
const words = (list) => `\\b(?:${[...list].sort((a, b) => b.length - a.length).join("|")})\\b`;

export function dumpTokens(prismio) {
  const output = execFileSync(prismio, ["dump-tokens"], { encoding: "utf8", env: { ...process.env, PRISMIO_INTERNAL_HOSTED: "1" } });
  return JSON.parse(output);
}

export function buildGrammar(tokens) {
  const control = new Set(["if", "else", "match", "while", "loop", "for", "in", "return", "break", "continue", "throw"]);
  const wordOperators = new Set(tokens.wordOperators);
  const literals = new Set(tokens.literals);
  const controlWords = tokens.keywords.filter((w) => control.has(w));
  const storageWords = tokens.keywords.filter((w) => !control.has(w) && !wordOperators.has(w) && !literals.has(w));

  const markers = tokens.contextualKeywords.filter((k) => /marker|visibility|qualifier|annotation/.test(k.context)).map((k) => k.word);
  const declarations = tokens.contextualKeywords.filter((k) => /^declaration/.test(k.context)).map((k) => k.word);
  const types = [...tokens.types.integer, ...tokens.types.float, ...tokens.types.other];
  const operators = [...new Set(tokens.operators.map((o) => o.text))].sort((a, b) => b.length - a.length).map(escape);

  const escapes = { match: "\\\\(?:x[0-9A-Fa-f]{2}|u\\{[0-9A-Fa-f]{1,6}\\}|[nrt0\\\\\"'])", name: "constant.character.escape.prismio" };
  return {
    $schema: "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
    name: "Prismio",
    scopeName: "source.prismio",
    // Generated by scripts/generate-grammar.mjs from `prismio dump-tokens`; do not edit.
    patterns: [{ include: "#comment" }, { include: "#string" }, { include: "#char" }, { include: "#number" },
               { include: "#declaration" }, { include: "#keyword" }, { include: "#type" }, { include: "#call" },
               { include: "#operator" }],
    repository: {
      comment: { name: "comment.line.double-slash.prismio", match: "//.*$" },
      string: { name: "string.quoted.double.prismio", begin: "\"", end: "\"|$", patterns: [escapes] },
      char: { name: "string.quoted.single.prismio", begin: "'", end: "'|$", patterns: [escapes] },
      number: {
        patterns: [
          { name: "constant.numeric.hex.prismio", match: "\\b0[xX][0-9A-Fa-f](?:_?[0-9A-Fa-f])*\\b" },
          { name: "constant.numeric.octal.prismio", match: "\\b0[oO][0-7](?:_?[0-7])*\\b" },
          { name: "constant.numeric.binary.prismio", match: "\\b0[bB][01](?:_?[01])*\\b" },
          { name: "constant.numeric.float.prismio", match: "\\b\\d(?:_?\\d)*\\.(?!\\.)\\d(?:_?\\d)*(?:[eE][+-]?\\d+)?\\b|\\b\\d(?:_?\\d)*[eE][+-]?\\d+\\b" },
          { name: "constant.numeric.decimal.prismio", match: "\\b\\d(?:_?\\d)*\\b" },
        ],
      },
      declaration: {
        patterns: [
          { match: "\\b(fn)\\s+([A-Za-z_][A-Za-z0-9_]*)", captures: { 1: { name: "storage.type.function.prismio" }, 2: { name: "entity.name.function.prismio" } } },
          { match: "\\b(struct|enum|trait|codeset|typelist)\\s+([A-Za-z_][A-Za-z0-9_]*)", captures: { 1: { name: "storage.type.prismio" }, 2: { name: "entity.name.type.prismio" } } },
          { match: `\\b(${declarations.join("|")})(?=\\s+[A-Za-z_])`, name: "storage.type.prismio" },
          { match: `\\b(${markers.join("|")})\\b(?=\\s+[A-Za-z_(])`, name: "storage.modifier.prismio" },
        ],
      },
      keyword: {
        patterns: [
          { name: "keyword.control.prismio", match: words(controlWords) },
          { name: "storage.type.prismio", match: words(storageWords) },
          { name: "keyword.operator.word.prismio", match: words(wordOperators) },
          { name: "constant.language.prismio", match: words(literals) },
          { name: "variable.language.self.prismio", match: "\\bself\\b|\\bSelf\\b" },
        ],
      },
      type: {
        patterns: [
          { name: "support.type.builtin.prismio", match: words(types) },
          { name: "entity.name.type.prismio", match: "\\b[A-Z][A-Za-z0-9_]*\\b" },
        ],
      },
      call: { match: "\\b([a-z_][A-Za-z0-9_]*)(?=\\s*(?:<[^>()]*>)?\\()", captures: { 1: { name: "entity.name.function.call.prismio" } } },
      operator: { name: "keyword.operator.prismio", match: operators.join("|") },
    },
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.includes("--refresh")) {
    const prismio = process.env.PRISMIO || "prismio";
    writeFileSync(tokensPath, JSON.stringify(dumpTokens(prismio), null, 2) + "\n");
  }
  const text = JSON.stringify(buildGrammar(JSON.parse(readFileSync(tokensPath, "utf8"))), null, 2) + "\n";
  if (args.includes("--check")) {
    let current = "";
    try { current = readFileSync(grammarPath, "utf8"); } catch { /* missing counts as stale */ }
    if (current !== text) {
      console.error("syntaxes/prismio.tmLanguage.json is stale: run `npm run grammar`");
      process.exit(1);
    }
  } else {
    writeFileSync(grammarPath, text);
  }
}
